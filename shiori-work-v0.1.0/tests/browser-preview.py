"""Offline UI tests. Does NOT access localhost or call a real model.
Run after `node scripts/build-preview.mjs` with Python + playwright + Chromium.
"""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parent.parent
shots=ROOT/'docs'/'screenshots'
shots.mkdir(parents=True,exist_ok=True)
results=[]
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1000},device_scale_factor=1)
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.set_content((ROOT/'preview.html').read_text(),wait_until='load')
    expect(page.locator('.hero')).to_be_visible()
    page.screenshot(path=str(shots/'01-home.png'),full_page=True,animations="disabled")
    results.append('Home shell, no JS errors, offline only')
    page.locator('.suggestion').first.click()
    expect(page.locator('#composer-input')).to_have_value('来週の設計レビューに向けて未決事項を整理してください。今回は調査までで、まだ改修はしません。')
    page.get_by_role('button',name='送信',exact=True).click()
    page.locator('.message-cards [data-action="open-work"]').first.wait_for()
    page.locator('.message-cards [data-action="open-work"]').first.click()
    expect(page.locator('.side-panel')).to_be_visible()
    page.screenshot(path=str(shots/'02-work-chat.png'),full_page=True,animations="disabled")
    results.append('Chat request -> draft work -> contextual conversation')
    page.get_by_role('button',name='作業を依頼',exact=True).click()
    page.get_by_role('button',name='確認へ進む',exact=True).click()
    expect(page.get_by_role('dialog')).to_contain_text('この内容で実行しますか')
    page.screenshot(path=str(shots/'03-approval.png'),full_page=True,animations="disabled")
    page.get_by_role('button',name='承認して1回実行',exact=False).click()
    expect(page.locator('.side-panel')).to_contain_text('受け入れ待ち',timeout=5000)
    page.locator('.message-cards [data-action="open-artifact"]').last.click()
    expect(page.get_by_role('dialog')).to_contain_text('実テスト')
    page.screenshot(path=str(shots/'04-result.png'),full_page=True,animations="disabled")
    page.get_by_role('dialog').get_by_role('button',name='閉じる',exact=True).click()
    results.append('Approval -> run -> artifact, not automatically done')
    page.locator('#composer-input').fill('根拠を詳しく追加して調査してください。')
    page.get_by_role('button',name='送信',exact=True).click()
    page.locator('.message-cards [data-action="open-approval"]').last.wait_for()
    page.locator('.message-cards [data-action="open-approval"]').last.click()
    page.get_by_role('button',name='承認して1回実行',exact=False).click()
    expect(page.locator('.side-panel')).to_contain_text('受け入れ待ち',timeout=5000)
    results.append('Follow-up in same work conversation')
    page.get_by_role('button',name='受け入れる',exact=True).click()
    for cb in page.locator('#accept-form input[type="checkbox"]').all():cb.check()
    page.locator('#accept-form textarea').fill('画面デモとして確認しました。')
    page.get_by_role('button',name='受け入れて完了',exact=True).click()
    expect(page.locator('.side-panel .badge').first).to_have_text('完了')
    results.append('Explicit acceptance with all criteria')
    page.get_by_role('button',name='定期確認',exact=True).click()
    page.get_by_role('button',name='定期確認を追加',exact=True).click()
    page.locator('#routine-form input[name="title"]').fill('未決事項を確認')
    page.get_by_role('button',name='定期確認を保存',exact=True).click()
    expect(page.locator('.routine-card')).to_have_count(1)
    page.locator('.routine-card [role="switch"]').click()
    expect(page.locator('.routine-card [role="switch"]')).to_have_attribute('aria-checked','true')
    results.append('Routine creation and enable/disable UX')
    page.get_by_role('button',name='ライブラリ',exact=True).click()
    expect(page.locator('.note-card')).to_have_count(2)
    page.keyboard.press('Control+k')
    page.locator('#search-input').fill('設計')
    expect(page.locator('.search-result').first).to_be_visible()
    page.keyboard.press('Escape')
    results.append('Library and keyboard search')
    page.get_by_role('button',name='相談',exact=True).click()
    page.locator('#composer-input').fill('下書きはここに残す')
    page.get_by_role('button',name='仕事',exact=True).click()
    page.get_by_role('button',name='相談',exact=True).click()
    expect(page.locator('#composer-input')).to_have_value('下書きはここに残す')
    results.append('Draft survives navigation')
    page.set_viewport_size({'width':390,'height':844})
    page.get_by_role('button',name='相談の履歴',exact=True).click()
    page.get_by_role('button',name='新しい相談',exact=True).click()
    expect(page.locator('.hero')).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'horizontal overflow'
    page.wait_for_timeout(3300)
    page.screenshot(path=str(shots/'05-mobile.png'),full_page=True,animations="disabled")
    results.append('390px mobile layout without horizontal overflow')
    assert not errors,errors
    results.append('No browser runtime exceptions in this sequence')
    browser.close()
(ROOT/'docs'/'browser-preview-results.json').write_text(json.dumps({'scope':'Offline HTML UI with in-memory simulation; not live-server browser E2E','results':results},ensure_ascii=False,indent=2))
print(json.dumps(results,ensure_ascii=False,indent=2))
